package com.portfolio.jobtracker.application;

import com.portfolio.jobtracker.application.dto.JobApplicationRequest;
import com.portfolio.jobtracker.application.dto.StatsResponse;
import com.portfolio.jobtracker.application.dto.StatusCount;
import com.portfolio.jobtracker.common.ResourceNotFoundException;
import com.portfolio.jobtracker.user.User;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

import java.time.*;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

/**
 * UNIT test: tests JobApplicationService in isolation.
 *
 * - No Spring context and no database are started, so these tests run in milliseconds.
 * - The repository is replaced with a Mockito "mock": a fake object whose return values we script
 *   with when(...).thenReturn(...) and whose calls we can check with verify(...).
 * - The Clock is fixed to a known date so date-based logic (weekly chart) is deterministic.
 */
@ExtendWith(MockitoExtension.class)
class JobApplicationServiceTest {

    /** Wednesday 2026-10-14. Its week starts on Monday 2026-10-12. */
    private static final Clock FIXED_CLOCK =
            Clock.fixed(Instant.parse("2026-10-14T12:00:00Z"), ZoneOffset.UTC);

    @Mock
    private JobApplicationRepository repository;

    private JobApplicationService service;
    private User user;

    @BeforeEach
    void setUp() {
        service = new JobApplicationService(repository, FIXED_CLOCK);
        user = new User("Test User", "test@example.com", "hash");
        // The id is normally generated by the database; set it manually for the test.
        ReflectionTestUtils.setField(user, "id", 1L);
    }

    @Test
    void create_defaultsStatusToApplied_andTrimsInput() {
        var request = new JobApplicationRequest("  Acme  ", " Developer ", " ", null, 50000,
                null, LocalDate.of(2026, 10, 1), null);
        // "Answer" with whatever entity was passed to save(), like a real repository would.
        when(repository.save(any(JobApplication.class))).thenAnswer(inv -> inv.getArgument(0));

        var response = service.create(user, request);

        // Capture the entity the service tried to save so we can inspect it.
        ArgumentCaptor<JobApplication> saved = ArgumentCaptor.forClass(JobApplication.class);
        verify(repository).save(saved.capture());
        assertThat(saved.getValue().getUser()).isSameAs(user);
        assertThat(response.company()).isEqualTo("Acme");
        assertThat(response.position()).isEqualTo("Developer");
        assertThat(response.location()).isNull();                 // blank strings become null
        assertThat(response.status()).isEqualTo(ApplicationStatus.APPLIED);
    }

    @Test
    void get_throwsNotFound_whenApplicationBelongsToAnotherUser() {
        // The repository query is scoped by user id, so another user's record simply isn't found.
        when(repository.findByIdAndUserId(99L, 1L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.get(user, 99L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessageContaining("99");
    }

    @Test
    void updateStatus_changesOnlyTheStatus() {
        JobApplication existing = new JobApplication(user);
        existing.setCompany("Acme");
        existing.setStatus(ApplicationStatus.APPLIED);
        when(repository.findByIdAndUserId(5L, 1L)).thenReturn(Optional.of(existing));
        when(repository.saveAndFlush(existing)).thenReturn(existing);

        var response = service.updateStatus(user, 5L, ApplicationStatus.INTERVIEW);

        assertThat(response.status()).isEqualTo(ApplicationStatus.INTERVIEW);
        assertThat(response.company()).isEqualTo("Acme");
    }

    @Test
    void delete_removesOwnedApplication() {
        JobApplication existing = new JobApplication(user);
        when(repository.findByIdAndUserId(5L, 1L)).thenReturn(Optional.of(existing));

        service.delete(user, 5L);

        verify(repository).delete(existing);
    }

    @Test
    void stats_computesTotalsResponseRateAndWeeklyBuckets() {
        when(repository.countByStatus(1L)).thenReturn(List.of(
                new StatusCount(ApplicationStatus.WISHLIST, 2),
                new StatusCount(ApplicationStatus.APPLIED, 5),
                new StatusCount(ApplicationStatus.INTERVIEW, 2),
                new StatusCount(ApplicationStatus.OFFER, 1)));
        // Chart window: 8 weeks, from Monday 2026-08-24 up to the current week (Monday 2026-10-12).
        when(repository.findAppliedDatesSince(eq(1L), eq(LocalDate.of(2026, 8, 24)))).thenReturn(List.of(
                LocalDate.of(2026, 10, 12),   // this week (Monday)
                LocalDate.of(2026, 10, 14),   // this week (Wednesday)
                LocalDate.of(2026, 8, 24)));  // first week in the window

        StatsResponse stats = service.stats(user);

        assertThat(stats.total()).isEqualTo(10);
        assertThat(stats.byStatus().get(ApplicationStatus.REJECTED)).isZero(); // missing statuses default to 0
        // 8 submitted (10 minus 2 wishlist), 3 progressed (2 interview + 1 offer) => 37.5%
        assertThat(stats.responseRate()).isEqualTo(37.5);
        assertThat(stats.perWeek()).hasSize(JobApplicationService.WEEKS_IN_CHART);
        assertThat(stats.perWeek().get(0).weekStart()).isEqualTo(LocalDate.of(2026, 8, 24));
        assertThat(stats.perWeek().get(0).count()).isEqualTo(1);
        assertThat(stats.perWeek().get(7).weekStart()).isEqualTo(LocalDate.of(2026, 10, 12));
        assertThat(stats.perWeek().get(7).count()).isEqualTo(2);
    }
}

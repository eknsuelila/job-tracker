CREATE TABLE users (
    -- GENERATED BY DEFAULT AS IDENTITY = auto-increment primary key (SQL standard syntax)
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,   -- UNIQUE also creates an index: fast login lookups
    password_hash VARCHAR(255) NOT NULL,          -- BCrypt hash (60 chars), never the plain password
    created_at    TIMESTAMP    NOT NULL
);

CREATE TABLE job_applications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Foreign key to the owner. ON DELETE CASCADE: deleting a user also deletes their applications.
    user_id      BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    company      VARCHAR(150)  NOT NULL,
    position     VARCHAR(150)  NOT NULL,
    location     VARCHAR(150),
    job_url      VARCHAR(500),
    salary       INTEGER,                         -- nullable: salary is often unknown
    status       VARCHAR(30)   NOT NULL,          -- enum name, e.g. 'INTERVIEW' (see ApplicationStatus.java)
    applied_date DATE          NOT NULL,
    notes        VARCHAR(2000),
    created_at   TIMESTAMP     NOT NULL,
    updated_at   TIMESTAMP     NOT NULL
);

-- Indexes match the most common queries: "my applications with status X" and
-- "my applications since date Y" (weekly chart). Both start with user_id because every
-- query is scoped to one user.
CREATE INDEX idx_job_applications_user_status ON job_applications (user_id, status);
CREATE INDEX idx_job_applications_user_applied ON job_applications (user_id, applied_date);
